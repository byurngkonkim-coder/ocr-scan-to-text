# D-10 결합에서 조심할 한 글자 단어 — 관형사·부사(앞 말)와 의존명사(뒤 말)
_STANDALONE_1CHAR = {"이", "그", "저", "한", "새", "첫", "옛", "몇", "또", "더", "덜", "못", "안",
                     "잘", "좀", "꼭", "왜", "다", "수", "곧", "참", "온", "딴", "늘"}
_BOUND_NOUNS_1CHAR = {"데", "바", "뿐", "줄", "수", "것", "때", "등"}
_MAX_ACCIDENTAL_SPLITS = 2   # 같은 띄어 쓴 형태가 이 횟수를 넘으면 OCR 우연이 아니라 저자 표기로 본다


def fix_split_tokens(text: str, document_corpus: str = "") -> str:
    """D-02, D-11, D-10 규칙을 적용하여 쪼개진 어절을 결합합니다."""
    if not text:
        return text

    # D-02: '번 역 :' -> '번역 :'
    text = _D02_LABEL_RE.sub(lambda m: re.sub(r"\s+", "", m.group(0)), text)

    # 특정 빈발 분리 쌍 우선 직결
    for (w1, w2), combined in _COMMON_SPLIT_PAIRS.items():
        text = re.sub(rf"(^|[\s\[\(\"\'가-힣]){re.escape(w1)}\s+{re.escape(w2)}(?=[.,!?\s\)\"\'\]가-힣]|$)", rf"\1{combined}", text)

    # D-10: 문서 내 증거 기반 결합 (document_corpus가 주어지거나 text 자체에서 추출)
    corpus = document_corpus if document_corpus else text
    tokens = re.findall(r'[가-힣]{2,8}', corpus)
    tok_counts = Counter(tokens)
    word_counts = None   # 독립 어절 빈도 — 필요할 때만 계산

    # 텍스트 줄 단위 순회하며 결합
    lines = text.splitlines()
    cleaned_lines = []

    for line in lines:
        words = line.split(" ")
        res = []
        i = 0
        while i < len(words):
            w = words[i]
            if not w:
                res.append(w)
                i += 1
                continue

            if i + 1 < len(words):
                w_next = words[i + 1]
                # 구두점 분리 보존
                m_next = re.match(r"^([가-힣]+)([.,!?~'\"]*)$", w_next)
                if m_next:
                    core_next = m_next.group(1)
                    punct_next = m_next.group(2)
                    joined = w + core_next

                    # 1) D-11 화이트리스트 조각 매치
                    # 앞 어절이 한글로 끝날 때만 — 'T. 의'·'쇄신, 의'·'299 히' 는 잘린 단어가 아니다
                    if core_next in _D11_BOUND_FRAGMENTS and re.search(r"[가-힣]$", w):
                        # 조사/어미가 앞 어절의 용언이나 체언 뒤에 붙는 형태인지 확인
                        # 예: '성공으로가 는' -> '성공으로 가는'
                        res.append(joined + punct_next)
                        i += 2
                        continue

                    # 2) D-10 문서 내 실증 결합 (결합형이 문서 내에 존재하는 경우)
                    # 띄어 쓴 형태가 더 많으면 결합하지 않는다 — OCR이 몇 번 붙여 읽은
                    # 이름('스펜서 존슨' 다수 vs '스펜서존슨' 2회)까지 붙이는 것 방지
                    # 띄어 쓴 형태가 3번 이상이면 저자의 표기다('측정 지표' 51회) — OCR 이 어절을 잘못 끊는
                    # 것은 우연이라 같은 자리에서 거듭 나오지 않는다 (정제본 23권: 복합명사 2,000여 곳을 붙였다)
                    spaced = corpus.count(f"{w} {core_next}")
                    if (len(joined) <= 8 and tok_counts.get(joined, 0) >= 2
                            and tok_counts[joined] >= spaced and spaced <= _MAX_ACCIDENTAL_SPLITS):
                        # 앞 말이 홀로 쓰이는 한 글자 단어('이 점을'·'또 한'·'한 번'·'수 없이')이고 뒤 말이
                        # 문서에서 독립 어절로도 자주 쓰이면 진짜 두 단어다 — 붙이면 뜻이 바뀐다('이점을').
                        # '그 래서' 의 '래서' 처럼 혼자 안 쓰이는 조각은 그대로 붙인다 (정제본 23권 실측)
                        if w in _STANDALONE_1CHAR or core_next in _BOUND_NOUNS_1CHAR:
                            if word_counts is None:
                                word_counts = Counter(re.findall(r'(?<![가-힣])[가-힣]+(?![가-힣])', corpus))
                            other = core_next if w in _STANDALONE_1CHAR else w
                            if word_counts.get(other, 0) >= 3:
                                res.append(w)
                                i += 1
                                continue
                        res.append(joined + punct_next)
                        i += 2
                        continue

            res.append(w)
            i += 1

        cleaned_lines.append(" ".join(res))

    return "\n".join(cleaned_lines)


# ─────────────────────────────────────────────────────────────────────────────
# 4. 과소 분리(붙어버린 어절) 띄어쓰기 분절 (Dictionary + Morphology MaxMatch)
# ─────────────────────────────────────────────────────────────────────────────

def _has_rieul(ch: str) -> bool:
    """한글 음절의 받침이 ㄹ인지 ('할', '볼', '을')."""
    code = ord(ch) - 0xAC00
    return 0 <= code < 11172 and code % 28 == 8


# 보조용언 및 의존명사 분리 패턴
AUX_PATTERNS = [
    # '머지않아'·'마지않다'·'못지않은'·'마지못해' 는 한 단어라 제외
    (re.compile(r"([가-힣]{1,})(?<![머마못])지\s*않(는다|았다|았고|았지만|으면|는|아|고|을|으니|은|았)"), r"\1지 않\2"),
    (re.compile(r"([가-힣]{1,})(?<![마])지\s*못(한다|했다|했고|하지만|하면|하는|해|하고|할|했)"), r"\1지 못\2"),
    # 의존명사 '수'는 ㄹ받침 관형형 뒤에만 온다 ('할수있다'). '변수없이'·'점수있는'은 보존
    (re.compile(r"([가-힣]+)(?<![실별])수\s*(있|없)([가-힣]*)"),   # '실수없이'·'별수없이' 는 한 단어
     lambda m: f"{m.group(1)} 수 {m.group(2)}{m.group(3)}" if _has_rieul(m.group(1)[-1]) else m.group(0)),
    (re.compile(r"([가-힣]{1,}(?:[ㄴ은]))\s*줄\s*(알|몰)(았다|랐다|았고|랐고|아|라|을|는)"), r"\1 줄 \2\3"),
    (re.compile(r"([가-힣]{1,}(?:[ㄴ은ㄹ을던]))\s*것\s*(같)"), r"\1 것 \2"),
    (re.compile(r"([가-힣]{1,}(?:[ㄴ은ㄹ을던]))\s*것(이|은|을|에|도|으|과)"), r"\1 것\2"),  # 조사는 붙여 씀
    # '때' 뒤 공백은 먹지 않는다 — '할 때 이미' 를 '때이미' 로 붙이던 것
    (re.compile(r"([가-힣]{1,}(?:[ㄹ을]))\s*때(문|이|는|에|도|까|부|였)"), r"\1 때\2"),
    (re.compile(r"([가-힣]{1,})때문(에|이다|이|을|의)"), r"\1 때문\2"),
    # 조사 뒤에서만 분리 ('이를위해' -> '이를 위해'). '확인해'·'거대해'는 보존
    (re.compile(r"([가-힣]+(?:으로|로|에|를|을))(위해|통해|대해|인해)"), r"\1 \2"),
    # 숫자 뒤 '이·가·에' 는 뺐다 — '3가지'·'500이라는'·'5.09에이커' 의 단어 첫 글자다.
    # '도·만' 도 뺐다 — '6,000도이므로'·'20만까지' 의 단위다
    (re.compile(r"([0-9]+(?:을|를|은|는|의|로|으로|와|과))([가-힣]{2,})"), r"\1 \2"),
    # '위해서는'·'대해서도' 처럼 '서…' 로 이어지면 한 어절이다 (정제본에서 1,700여 곳을 '위해 서는' 으로 쪼갰다)
    # 조사 뒤나 어절 첫머리의 '대해' 만 — '비대해지면'·'거대해지면' 의 '대해' 는 단어 속이다
    (re.compile(r"((?:(?<=[을를에로])|(?<![가-힣]))(?:통해|위해|대해|인해))(?!서|지|주)([가-힣]{2,})"), r"\1 \2"),   # '대해주지만' 보존
    (re.compile(r"(해야|할지|할까|했을지)몰라"), r"\1 몰라"),
    (re.compile(r"(오늘|내일|어제|지금)\s*(내|나|우리)"), r"\1 \2"),
    (re.compile(r"([가-힣]{2,}[을를])\s*(빛내|위로하|다독이|풍요롭게|살아가|느낄|담았|만날|읽|이끌)"), r"\1 \2"),
    (re.compile(r"([가-힣]{2,}[이가])\s*(필요|부족|충분|가능|어렵|쉽)"), r"\1 \2"),
    (re.compile(r"(더|함께|다시)\s*(깊이|담았|읽|나누|보낼)"), r"\1 \2"),
]

# 한국어 대표 조사 목록 (긴 것부터 매칭)
