"""core/korean_spacing_corrector.py - AI Agent 없는 로컬 한국어 띄어쓰기 및 맞춤법 교정기.

기능 요약:
1. fix_ocr_quotes_and_symbols:
   - OCR 시 큰따옴표(“ ”)가 66 / 99 로 오인식되는 전형적인 스캔 버그 교정
   - 한글과 괄호, 한글과 숫자 사이의 부자연스러운 붙음 정규화 (예: '매뉴얼30을' -> '매뉴얼 30을')
2. fix_spelling_and_typos:
   - OCR 빈발 오탈자 및 한국어 표준 맞춤법 교정 ('훌륨한' -> '훌륭한', '띨어쓰기' -> '띄어쓰기' 등)
3. fix_split_tokens (과다 띄어쓰기 / 어절 쪼개짐 교정):
   - D-02: 단일 음절 연속 나열 결합 ('번 역 :' -> '번역 :')
   - D-11: 자립 불가 어미/조사 단독 토큰 앞 어절 결합 ('가 는' -> '가는', '기 본적인' -> '기본적인')
   - D-10: 문서 내 어절 빈도 기반 쪼개진 어절 결합 ('세일 즈' -> '세일즈')
4. split_concatenated_korean (과소 띄어쓰기 / 붙어버린 어절 분리):
   - 관형사 분리 ('이책은' -> '이 책은', '모든세일즈' -> '모든 세일즈')
   - 보조용언 및 의존명사 분리 ('되지않는다' -> '되지 않는다', '수있다' -> '수 있다')
   - 조사/어미/품사 패턴 기반 장문 토큰 분절 ('세일즈에입문한세일즈맨들은무엇을해야할지몰라')
5. refine_korean_text:
   - 위 모든 단계를 통합한 오프라인 올인원 정제 파이프라인
"""
