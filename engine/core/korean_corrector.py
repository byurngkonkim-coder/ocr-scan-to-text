# 띄어쓰기가 통째로 빠진 덩어리로 볼 최소 길이 ('이책은초보세일즈맨을위한매뉴얼이다' 17자).
# 10자로 두면 '마이크로프로세서에만'·'스탠퍼드대학교로부터' 같은 정상 어절을 쪼갰다
_RUNON_MIN = 12


def _segment_long_token(token: str) -> str:
    """띄어쓰기 없이 붙어버린 6자 이상의 순한글 단어를 의미 단위로 분절합니다."""
    if len(token) < 5 or not re.match(r"^[가-힣]+$", token):
        return token

    # 1. 관형사 선두 분리 (예: '이책은' -> '이 책은', '모든세일즈' -> '모든 세일즈')
    for det in ["모든", "온갖", "이", "그", "저", "새", "헌", "첫"]:
        if token.startswith(det) and len(token) > len(det) + 1:
            rest = token[len(det):]
            # 한 글자 관형사는 뒤가 알려진 단어일 때만 분리 ('이책은'은 분리, '저장되었습니다'는 보존)
            if len(det) == 1 and not any(rest.startswith(w) for w in COMMON_WORDS):
                continue
            # 남은 부분이 유효한 단어이거나 조사가 붙은 어절인지 검사
            return det + " " + _segment_long_token(rest)

    # 2·3 은 띄어쓰기가 통째로 빠진 긴 덩어리에만 적용한다. 6~9자는 정상 어절이 대부분이라
    # ('경영자들에게'·'마이크로소프트는'·'사람들에게는') 사전 접두어·조사 글자로 쪼개면 망가진다.
    # 정제본 23권 실측(2026-10-10): 이 두 규칙이 정상 어절 3,867곳을 쪼갰다.
    if len(token) < _RUNON_MIN:
        return token

    # 2. 알려진 복합 명사/동사 결합 분리 (사전 기반 최장 일치)
    # 예: '세일즈에입문한세일즈맨들은무엇을해야할지몰라'
    # 앞에서부터 탐색
    for length in range(min(len(token) - 2, 8), 1, -1):
        prefix = token[:length]
        # 접두사가 알려진 단어인 경우
        if prefix in COMMON_WORDS:
            rest = token[length:]
            # 조사 확인: 접두사 바로 뒤에 조사가 붙어 있는지
            josa_found = None
            for j in JOSA_LIST:
                if rest.startswith(j) and len(rest) > len(j):
                    # 조사 뒤 남은 부분이 한글 2자 이상인 경우
                    rem = rest[len(j):]
                    if len(rem) >= 2:
                        josa_found = j
                        break
            if josa_found:
                split_point = length + len(josa_found)
                return token[:split_point] + " " + _segment_long_token(token[split_point:])
            elif len(rest) >= 2:
                # 조사가 없더라도 접두사가 완전한 단어이고 뒤도 단어로 시작하면 분리
                return prefix + " " + _segment_long_token(rest)

    # 3. '조사+동사' 경계 탐색 (예: '~에입문한', '~을통해', '~에서성공으로')
    for josa in ["에서", "으로", "에게", "부터", "까지", "을", "를", "에", "의", "로", "와", "과"]:
        idx = token.find(josa)
        if 2 <= idx <= len(token) - len(josa) - 2:
            left = token[:idx + len(josa)]
            right = token[idx + len(josa):]
            if len(right) >= 2 and not right.startswith(("서", "부터")):   # '으로서'·'에서'·'으로부터' 를 자르지 않는다
                # 분리 후보 유효성 검증
                return _segment_long_token(left) + " " + _segment_long_token(right)

    return token


def split_concatenated_korean(text: str) -> str:
    """붙어버린 어절, 보조용언, 관형사를 한국어 어법에 맞게 띄어 씁니다."""
    if not text:
        return text

    # (1) 보조용언 및 의존명사 정규식 분리
    for pat, repl in AUX_PATTERNS:
        text = pat.sub(repl, text)

    # (2) 어절 단위 긴 토큰 분절
    lines = text.splitlines()
    out_lines = []

    for line in lines:
        tokens = line.split(" ")
        new_tokens = []
        for t in tokens:
            # 괄호나 구두점이 붙어 있는 경우 분리하여 처리
            m = re.match(r"^([^\w가-힣]*)([가-힣]+)([^\w가-힣]*)$", t)
            if m and len(m.group(2)) >= 6:
                prefix, core, suffix = m.group(1), m.group(2), m.group(3)
                seg = _segment_long_token(core)
                new_tokens.append(f"{prefix}{seg}{suffix}")
            else:
                new_tokens.append(t)
        out_lines.append(" ".join(new_tokens))

    return "\n".join(out_lines)


