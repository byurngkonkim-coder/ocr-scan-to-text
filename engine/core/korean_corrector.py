# 1. OCR 오인식 따옴표 및 기호 정규화
# ─────────────────────────────────────────────────────────────────────────────

def fix_ocr_quotes_and_symbols(text: str) -> str:
    """OCR 시 따옴표가 66/99로 오인식된 경우 및 기호 경계를 정규화합니다."""
    if not text:
        return text

    # (1)(2) 큰따옴표 66 ... 99 -> " ... "
    # 한 줄 안에서 여는 66과 닫는 99가 짝을 이룰 때만 교정한다.
    # 단독 66/99는 실제 숫자('66명', '1999 년')일 수 있으므로 건드리지 않는다.
    text = re.sub(r'(^|[\s\(\[\{])66([가-힣A-Za-z][^\n]*?[가-힣A-Za-z.!?…])99(?=[\s\)\]\}.,!?]|$)',
                  r'\1"\2"', text, flags=re.M)

    # (3) 괄호와 한글 사이 공백 분리
    # 예: '입문자들이[세일즈' -> '입문자들이 [세일즈'
    text = re.sub(r'([가-힣0-9])(\[|\()', r'\1 \2', text)
    # 예: '매뉴얼30]을' -> '매뉴얼 30]을' (닫는 괄호 뒤는 조사가 올 수 있으므로 유지하되 여는 괄호 앞은 분리)

    # (4) 한글과 숫자 경계 분리 (단, 날짜/단위/수량 등은 적절히 보존)
    # 예: '매뉴얼30을' -> '매뉴얼 30을', '제1장' -> 보존
    text = re.sub(r'([가-힣]{2,})([0-9]{1,4})(을|를|이|가|은|는|에|의|로|으로|와|과|도|만)', r'\1 \2\3', text)

    return text


