def refine_korean_text(text: str, document_corpus: str = "") -> str:
    """AI Agent(외부 LLM) 없이 순수 로컬 알고리즘으로 한국어 띄어쓰기, 맞춤법, 어절 결합을 완결합니다."""
    if not text:
        return text

    # 1단계: OCR 기호 및 따옴표(66/99) 교정
    text = fix_ocr_quotes_and_symbols(text)

    # 2단계: 맞춤법 및 OCR 오탈자 사전 교정
    text = fix_spelling_and_typos(text)

    # 3단계: 과다 분리(쪼개진 단어) 결합 (D-02, D-10, D-11)
    text = fix_split_tokens(text, document_corpus=document_corpus)

    # 4단계: 과소 분리(붙어버린 단어) 띄어쓰기 분절
    text = split_concatenated_korean(text)

    # 6단계: 한국어 조사 밀착 및 어휘 경계 정규화
    # 조사는 앞 명사에 붙여 씀: '세일즈맨 에게' -> '세일즈맨에게'
    text = re.sub(r'([가-힣0-9])\s+(에게|에게는|에게서|에게도|에서는|에서도)', r'\1\2', text)
    # 복수 접미사 결합: '세일즈맨 들은' -> '세일즈맨들은'
    text = re.sub(r'([가-힣]{2,})\s+(들은|들이|들을|들에게)', r'\1\2', text)
    # 일반 명사 앞 조사 분리: '책은초보' -> '책은 초보', '하루를위로하는' -> '하루를 위로하는'
    text = re.sub(r'([가-힣]+?)(들은|들이|들을|들에게|은|는|이|가|을|를|에|의|로|으로|와|과|도|만)\s*(초보|선배|고객|사람|세일즈|성공|해법|매뉴얼|입문|무엇|어디|누구|어떻게|위로|다독|희망|사랑|마음|생각|노력|인생|세상|그림|명언|하루)', r'\1\2 \3', text)
    # 용언 관형형 뒤 체언 분리: '위로하는그림' -> '위로하는 그림', '다독이는명언' -> '다독이는 명언'
    text = re.sub(r'([가-힣]{2,}(?:하는|되는|있는|없는|않는|했던|다독이는|빛내는|살아가는))\s*(?!구나|군|데|지)([가-힣]{2,})', r'\1 \2', text)
    # 대표 체언 간 경계 분리: '그림하루를' -> '그림 하루를'
    text = re.sub(r'(그림|명언|사진|책|글|시|소설|작품|인생|마음)\s*(하루|매일|오늘|내일|삶|사랑)', r'\1 \2', text)
    # 직급/수식어 분리: '초보세일즈맨' -> '초보 세일즈맨'
    text = re.sub(r'(초보|수석|전문|선임|책임)\s*(세일즈|마케팅|개발자|엔지니어|디자이너)', r'\1 \2', text)
    # 섹션 표제어 및 약어 분리: '감사의글' -> '감사의 글', '부록CIC' -> '부록 CIC'
    text = re.sub(r'감사의글', '감사의 글', text)
    text = re.sub(r'(부록|목차|참고)([A-Za-z가-힣])', r'\1 \2', text)
    # 영문 약어 뒤 조사 분리: 'CIC를위한' -> 'CIC를 위한'
    text = re.sub(r'([A-Za-z]+(?:를|을|이|가|은|는|에|의|로|과|와))\s*([가-힣]{2,})', r'\1 \2', text)
    # 접속부사 '및' 분리: '정보활용및분석' -> '정보활용 및 분석'
    text = re.sub(r'([가-힣]{2,})및([가-힣]{2,})', r'\1 및 \2', text)
    # 연어(Collocation) 분리: '살아있는정보' -> '살아있는 정보'
    text = re.sub(r'(살아있는|살아 있는|죽어있는)\s*([가-힣]{2,})', r'\1 \2', text)
    text = re.sub(r'(위한|통한|대 한|인한)(?![다니지])\s*([가-힣]{2,})', r'\1 \2', text)  # '통한다고'는 보존
    # 의문사/대명사 뒤 동사 분리: '무엇을해야' -> '무엇을 해야'
    text = re.sub(r'(무엇을|어디서|어떻게|왜)\s*(해야|할지|하는|할까)', r'\1 \2', text)
    # '해야할지' -> '해야 할지'
    text = re.sub(r'(해야)\s*(할지|하는|할까|한다)', r'\1 \2', text)

    # 공백 연속 정리
    text = re.sub(r"(?<=\S) {2,}", " ", text)

    return text
